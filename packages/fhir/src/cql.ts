const SYNTAX: ProgramSyntax = {
    keywords: KEYWORDS,
    operator: /^(?:!=|!~|<=|>=|[=~<>+\-*/&|^])/,
    punctuation: /^[,:]/,
    number: /^\d+(?:\.\d+|L)?/,
    quotedName: /^(?:"(?:[^"\\]|\\.)*"|`(?:[^`\\]|\\.)*`)/,
    binding: null,
}

/**
 * CQL as a CodeMirror stream parser: a single-quoted text is a string, a double-quoted or
 * backticked one is a name, a name followed by `(` is a function, a name after `.` is a member even
 * when it is spelled like a keyword, and `@2026-01-01` is a date.
 */
export const cqlParser: StreamParser<ProgramState> & { name: string } = {
    name: 'cql',
    startState,
    copyState,
    token: (stream, state) => programToken(stream, state, SYNTAX),
    languageData: {
        commentTokens: COMMENT_TOKENS,
        closeBrackets: { brackets: ['(', '[', '{', "'", '"', '`'] },
    },
}

/** CQL as a plugin's language: `language="cql"`, written as `text/cql`, `text/cql-expression` or `application/cql`. */
export const cqlLanguage: PluginLanguage = {
    name: 'cql',
    language: cqlParser as StreamParser<unknown> & { name: string },
    mediaTypes: ['text/cql', 'text/cql-expression', 'application/cql'],
}
