/**
 * Write the candidate themes Storybook offers beside the library's own: every theme an app
 * stylesheet defines, under `html[data-theme='<app>-<name>']`, so it can be judged on the
 * library's components before it is adopted into tokens/tokens.json. The app's own theme is
 * named `base`. Nothing here ships with the package.
 *
 *   bun scripts/import-candidates.ts <app>=<path to its index.css> ...
 *
 * Writes .storybook/candidates.css and .storybook/candidates.json.
 */
import { readFileSync, writeFileSync } from 'node:fs'

type Vars = Record<string, string>

/** Every top-level `selector { ... }` block holding custom properties, comments removed. */
function blocks(css: string): { selector: string; vars: Vars }[] {
    const text = css.replace(/\/\*[\s\S]*?\*\//g, '')
    const found: { selector: string; vars: Vars }[] = []
    for (const match of text.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
        const vars: Vars = {}
        for (const line of match[2].split(';')) {
            const at = line.indexOf(':')
            if (at === -1) continue
            const name = line.slice(0, at).trim()
            if (name.startsWith('--')) vars[name.slice(2)] = line.slice(at + 1).trim()
        }
        if (Object.keys(vars).length > 0) found.push({ selector: match[1].trim().replace(/\s+/g, ' '), vars })
    }
    return found
}

/** The themes one stylesheet defines, light and dark, by name. */
function themes(css: string, base: string | null): Map<string, { light: Vars; dark: Vars }> {
    const out = new Map<string, { light: Vars; dark: Vars }>()
    const entry = (name: string) => {
        if (!out.has(name)) out.set(name, { light: {}, dark: {} })
        return out.get(name) as { light: Vars; dark: Vars }
    }
    for (const { selector, vars } of blocks(css)) {
        const last = selector.split(/[;}]/).pop()?.trim() ?? ''
        const named = /data-(?:theme|palette)='([\w-]+)'/.exec(last)?.[1]
        const dark = last.includes('.dark')
        if (named !== undefined) {
            const name = named === base ? 'base' : named
            Object.assign(entry(name)[dark ? 'dark' : 'light'], vars)
        } else if (last === ':root') Object.assign(entry('base').light, vars)
        else if (last === '.dark') Object.assign(entry('base').dark, vars)
    }
    return out
}

function block(selector: string, vars: Vars): string {
    return `${selector} {\n${Object.entries(vars)
        .map(([name, value]) => `    --${name}: ${value};`)
        .join('\n')}\n}\n`
}

const parts = ["/* Generated by scripts/import-candidates.ts from the apps' stylesheets. Storybook only. */\n"]
const listed: { value: string; title: string; app: string }[] = []
for (const arg of process.argv.slice(2)) {
    const [spec, path] = arg.split('=')
    const [app, base] = spec.split(':')
    if (app === undefined || path === undefined) throw new Error(`expected <app>[:<base theme>]=<path>, got ${arg}`)
    for (const [name, theme] of themes(readFileSync(path, 'utf8'), base ?? null)) {
        const value = `${app}-${name}`
        parts.push(block(`html:not(.dark)[data-theme='${value}']`, theme.light), block(`html.dark[data-theme='${value}']`, theme.dark))
        listed.push({ value, title: name.charAt(0).toUpperCase() + name.slice(1), app })
    }
}
writeFileSync('.storybook/candidates.css', parts.join('\n'))
writeFileSync('.storybook/candidates.json', `${JSON.stringify(listed, null, 4)}\n`)
console.log(`wrote ${listed.length} candidate themes: ${listed.map((entry) => entry.value).join(', ')}`)
