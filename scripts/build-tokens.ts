/**
 * Write the core package's token CSS from its tokens/tokens.json, the one place a token is defined.
 * Under packages/core:
 *
 *   src/styles/tokens.css           the default theme and the density levels, which styles.css carries
 *   src/styles/themes/<name>.css    every other theme, one file each, so an app carries only the themes it imports
 *   src/styles/themes.css           every theme's file, for an app that offers them all
 *
 * `default` answers on `:root` and `.dark`. Every other theme answers on `html[data-theme]` for
 * the whole app, overriding what it changes; a token it sets in light but not in dark takes the
 * default's dark value, so a theme never carries a light value into dark mode. Every theme also
 * answers on `[data-theme-scope]` for one element and what is inside it, as a theme picker's
 * preview swatch is. A theme may override any token, the density levels' included.
 *
 *   bun scripts/build-tokens.ts          write the CSS
 *   bun scripts/build-tokens.ts --check  fail when the CSS is not what the tokens make
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

type Vars = Record<string, string>
interface Tokens {
    theme: Vars
    themes: Record<string, { light: Vars; dark: Vars }>
    density: Record<string, Vars | string> & { default: string }
}

const CORE = join(import.meta.dirname, '..', 'packages', 'core')
const STYLES = join(CORE, 'src', 'styles')
const THEMES = join(STYLES, 'themes')
const tokens = JSON.parse(readFileSync(join(CORE, 'tokens', 'tokens.json'), 'utf8')) as Tokens

const HEADER = '/* Generated by scripts/build-tokens.ts from tokens/tokens.json. Edit the JSON, not this file. */\n'

function block(selectors: string[], vars: Vars): string {
    const lines = Object.entries(vars).map(([name, value]) => `    --${name}: ${value};`)
    return `${selectors.join(',\n')} {\n${lines.join('\n')}\n}\n`
}

const base = tokens.themes.default
if (base === undefined) throw new Error('tokens.json has no default theme')
const others = Object.entries(tokens.themes).filter(([name]) => name !== 'default')

/** A theme's dark tokens, with the default's dark value for every token it sets in light alone. */
function darkOf(theme: { light: Vars; dark: Vars }): Vars {
    const dark: Vars = { ...theme.dark }
    for (const key of Object.keys(theme.light)) {
        if (!(key in dark)) dark[key] = base.dark[key] ?? base.light[key]
    }
    return dark
}

/** One element's theme: the whole set, so it shows that theme whatever the page around it uses. */
function scope(name: string, theme: { light: Vars; dark: Vars }): string[] {
    return [
        block([`[data-theme-scope='${name}']`], { ...base.light, ...theme.light }),
        block([`.dark [data-theme-scope='${name}']`], { ...base.light, ...base.dark, ...theme.light, ...darkOf(theme) }),
    ]
}

/** Every file the tokens make, by path. */
const files = new Map<string, string>()

// Density: the default level answers on `:root`, every level on its own `[data-density]`.
const levels = Object.keys(tokens.density).filter((key) => key !== 'default' && !key.startsWith('$'))
const prefixed = (vars: Vars): Vars => Object.fromEntries(Object.entries(vars).map(([name, value]) => [`density-${name}`, value]))

files.set(
    join(STYLES, 'tokens.css'),
    [
        HEADER,
        '@custom-variant dark (&:is(.dark *));\n',
        block(['@theme inline'], tokens.theme),
        block([':root'], base.light),
        block(['.dark'], base.dark),
        ...scope('default', base),
        block([':root'], prefixed(tokens.density[tokens.density.default] as Vars)),
        ...levels.map((level) => block([`html[data-density='${level}']`], prefixed(tokens.density[level] as Vars))),
    ].join('\n'),
)

// A whole app's theme on `html`: the overrides alone, over the default on `:root`, which its
// selectors outrank wherever the file is imported.
for (const [name, theme] of others) {
    files.set(
        join(THEMES, `${name}.css`),
        [
            HEADER,
            block([`html[data-theme='${name}']`], theme.light),
            block([`html.dark[data-theme='${name}']`], darkOf(theme)),
            ...scope(name, theme),
        ].join('\n'),
    )
}

files.set(join(STYLES, 'themes.css'), [HEADER, ...others.map(([name]) => `@import './themes/${name}.css';\n`)].join(''))

/** Theme files no theme in the tokens makes any more. */
const stale = existsSync(THEMES)
    ? readdirSync(THEMES)
          .map((file) => join(THEMES, file))
          .filter((path) => !files.has(path))
    : []

if (process.argv.includes('--check')) {
    const wrong = [...files].filter(([path, css]) => !existsSync(path) || readFileSync(path, 'utf8') !== css).map(([path]) => path)
    if (wrong.length > 0 || stale.length > 0) {
        console.error(`${[...wrong, ...stale].join(', ')}: not what tokens/tokens.json makes: run bun run tokens`)
        process.exit(1)
    }
    console.log(`the token CSS matches tokens/tokens.json: ${files.size} files`)
} else {
    mkdirSync(THEMES, { recursive: true })
    for (const [path, css] of files) writeFileSync(path, css)
    for (const path of stale) rmSync(path)
    console.log(`wrote the token CSS: tokens.css, themes.css and ${others.length} themes, with ${levels.length} density levels`)
}
