/**
 * Write src/styles/tokens.css from tokens/tokens.json, the one place a token is defined.
 *
 * The first palette is the default: it answers on `:root` and `.dark` as well as on its own
 * `[data-palette]`. Every other palette answers on `html[data-theme]` for a whole app and on
 * `[data-palette]` for a subtree.
 *
 *   bun scripts/build-tokens.ts          write the CSS
 *   bun scripts/build-tokens.ts --check  fail when the CSS is not what the tokens make
 */
import { readFileSync, writeFileSync } from 'node:fs'

type Vars = Record<string, string>
interface Tokens {
    theme: Vars
    common: { light: Vars; dark: Vars }
    palettes: Record<string, { light: Vars; dark: Vars }>
    density: Record<string, Vars | string> & { default: string }
}

const OUT = 'src/styles/tokens.css'
const tokens = JSON.parse(readFileSync('tokens/tokens.json', 'utf8')) as Tokens

function block(selectors: string[], vars: Vars): string {
    const lines = Object.entries(vars).map(([name, value]) => `    --${name}: ${value};`)
    return `${selectors.join(',\n')} {\n${lines.join('\n')}\n}\n`
}

const names = Object.keys(tokens.palettes)
const [first] = names
const parts: string[] = [
    '/* Generated by scripts/build-tokens.ts from tokens/tokens.json. Edit the JSON, not this file. */\n',
    '@custom-variant dark (&:is(.dark *));\n',
    block(['@theme inline'], tokens.theme),
    block([':root'], tokens.common.light),
    block(['.dark'], tokens.common.dark),
]
for (const name of names) {
    const palette = tokens.palettes[name]
    const isDefault = name === first
    parts.push(
        block(
            isDefault ? [':root', `[data-palette='${name}']`] : [`html[data-theme='${name}']`, `[data-palette='${name}']`],
            palette.light,
        ),
        block(
            isDefault
                ? ['.dark', `.dark [data-palette='${name}']`]
                : [`html.dark[data-theme='${name}']`, `.dark [data-palette='${name}']`],
            palette.dark,
        ),
    )
}
// Density: the default answers on `:root`, every level on its own `[data-density]`.
const levels = Object.keys(tokens.density).filter((key) => key !== 'default' && !key.startsWith('$'))
const prefixed = (vars: Vars): Vars =>
    Object.fromEntries(Object.entries(vars).map(([name, value]) => [`density-${name}`, value]))
parts.push(block([':root'], prefixed(tokens.density[tokens.density.default] as Vars)))
for (const level of levels) parts.push(block([`[data-density='${level}']`], prefixed(tokens.density[level] as Vars)))
const css = parts.join('\n')

if (process.argv.includes('--check')) {
    const held = readFileSync(OUT, 'utf8')
    if (held !== css) {
        console.error(`${OUT} is not what tokens/tokens.json makes: run bun run tokens`)
        process.exit(1)
    }
    console.log(`${OUT} matches tokens/tokens.json`)
} else {
    writeFileSync(OUT, css)
    console.log(`wrote ${OUT}: ${names.length} palettes, ${Object.keys(tokens.theme).length} theme entries`)
}
