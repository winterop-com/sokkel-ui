/**
 * Write the core package's token CSS from its tokens/tokens.json, the one place a token is defined.
 * Under packages/core:
 *
 *   src/styles/tokens.css           tidevann, the base theme, and the density levels, which styles.css carries
 *   src/styles/themes/<name>.css    every other theme, one file each, so an app carries only the themes it imports
 *   src/styles/themes.css           every theme's file, for an app that offers them all
 *   src/lib/theme-list.ts           every theme's name and label, for a theme picker
 *   src/lib/breakpoints.ts          the breakpoints in px, for a media query a script asks
 *   src/lib/durations.ts            the waits in ms a script holds for (busy-release, wait-shown, tip-hold)
 *
 * `tidevann`, the base theme, answers on `:root` and `.dark`, so a page with no `data-theme` wears
 * it, and so do `html[data-theme='tidevann']` and `[data-theme-scope='tidevann']`. Every other theme
 * answers on `html[data-theme]` for the whole app, overriding what it changes; a token it sets in
 * light but not in dark takes tidevann's dark value, so a theme never carries a light value into
 * dark mode. Every theme also answers on `[data-theme-scope]` for one element and what is inside
 * it, as a theme picker's preview swatch is, in the same rule as its `html` one: every scope first
 * takes tidevann's whole set, at no specificity, so a scope shows its own theme whatever the page
 * around it wears, and its theme's overrides go over that. A theme may override any token, the
 * density levels' included. A density level answers on `html[data-density]` for the whole app and
 * on `[data-density-scope]` for one element and what is inside it, so one part can be shown at
 * another level than the page around it.
 *
 * Tidevann sets its surfaces (canvas, node, panel ground and line, critical wash) as fixed
 * colors; every other theme takes them from `derived`, mixed from its own colors, unless it sets
 * one itself.
 *
 * An elevation is written as its layers, each an x, y, blur and spread in px and a color, so a
 * renderer that reads no CSS takes the same shadow; the CSS writes it as a box-shadow.
 *
 *   bun scripts/build-tokens.ts          write the CSS
 *   bun scripts/build-tokens.ts --check  fail when the CSS is not what the tokens make
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/** One layer of an elevation: its offset, blur and spread in px, and its color. */
interface ShadowLayer {
    x: number
    y: number
    blur: number
    spread: number
    color: string
}
type Vars = Record<string, string | ShadowLayer[]>
interface Tokens {
    theme: Vars
    themes: Record<string, { $label?: string; $description?: string; light: Vars; dark: Vars }>
    derived: { light: Vars; dark: Vars }
    density: Record<string, Vars | string> & { default: string }
}

const CORE = join(import.meta.dirname, '..', 'packages', 'core')
const STYLES = join(CORE, 'src', 'styles')
const THEMES = join(STYLES, 'themes')
const tokens = JSON.parse(readFileSync(join(CORE, 'tokens', 'tokens.json'), 'utf8')) as Tokens

const HEADER = '/* Generated by scripts/build-tokens.ts from tokens/tokens.json. Edit the JSON, not this file. */\n'

const px = (n: number) => (n === 0 ? '0' : `${String(n)}px`)

/** A token's value as CSS: an elevation's layers as a box-shadow (a spread of 0 left out), every other value as it is written. */
function css(value: string | ShadowLayer[]): string {
    if (typeof value === 'string') return value
    return value
        .map((layer) =>
            [px(layer.x), px(layer.y), px(layer.blur), ...(layer.spread === 0 ? [] : [px(layer.spread)]), layer.color].join(' '),
        )
        .join(', ')
}

function block(selectors: string[], vars: Vars): string {
    const lines = Object.entries(vars).map(([name, value]) => `    --${name}: ${css(value)};`)
    return `${selectors.join(',\n')} {\n${lines.join('\n')}\n}\n`
}

/** The base theme, which defines every token. */
const BASE = 'tidevann'
const base = tokens.themes[BASE]
if (base === undefined) throw new Error(`tokens.json has no ${BASE} theme`)
const others = Object.entries(tokens.themes)
    .filter(([name]) => name !== BASE)
    .map(([name, theme]) => [name, withDerived(theme)] as const)

/** A theme with the derived surfaces under what it sets itself. */
function withDerived(theme: { light: Vars; dark: Vars }): { light: Vars; dark: Vars } {
    const own = (vars: Vars): Vars => Object.fromEntries(Object.entries(vars).filter(([name]) => !name.startsWith('$')))
    return { light: { ...own(tokens.derived.light), ...theme.light }, dark: { ...own(tokens.derived.dark), ...theme.dark } }
}

/** A theme's dark tokens, with tidevann's dark value for every token it sets in light alone. */
function darkOf(theme: { light: Vars; dark: Vars }): Vars {
    const dark: Vars = { ...theme.dark }
    for (const key of Object.keys(theme.light)) {
        if (!(key in dark)) dark[key] = base.dark[key] ?? base.light[key]
    }
    return dark
}

/** Every file the tokens make, by path. */
const files = new Map<string, string>()

// Density: the default level answers on `:root`, every level on its own `[data-density]` and on its own scope.
const levels = Object.keys(tokens.density).filter((key) => key !== 'default' && !key.startsWith('$'))
const prefixed = (vars: Vars): Vars => Object.fromEntries(Object.entries(vars).map(([name, value]) => [`density-${name}`, value]))

files.set(
    join(STYLES, 'tokens.css'),
    [
        HEADER,
        '@custom-variant dark (&:is(.dark *));\n',
        block(['@theme inline'], tokens.theme),
        // Every scope, of whichever theme, starts from tidevann's whole set, so no token of the
        // page's theme reaches into it; `:where` keeps these under any theme's own scope rule.
        block([':root', ':where([data-theme-scope])'], base.light),
        block(['.dark', ':where(.dark [data-theme-scope])'], base.dark),
        block([':root'], prefixed(tokens.density[tokens.density.default] as Vars)),
        ...levels.map((level) =>
            block([`html[data-density='${level}']`, `[data-density-scope='${level}']`], prefixed(tokens.density[level] as Vars)),
        ),
    ].join('\n'),
)

// A theme's overrides, once for light and once for dark, each on the whole app's `html` and on one
// element's scope. Its selectors outrank tidevann on `:root` and the scopes' tidevann set
// wherever the file is imported.
for (const [name, theme] of others) {
    files.set(
        join(THEMES, `${name}.css`),
        [
            HEADER,
            block([`html[data-theme='${name}']`, `[data-theme-scope='${name}']`], theme.light),
            block([`html.dark[data-theme='${name}']`, `.dark [data-theme-scope='${name}']`], darkOf(theme)),
        ].join('\n'),
    )
}

files.set(join(STYLES, 'themes.css'), [HEADER, ...others.map(([name]) => `@import './themes/${name}.css';\n`)].join(''))

// Every theme by name, label and description, tidevann first, as a picker offers them. A theme's
// label is its `$label`, or its name with a capital; its description, its `$description`, says how
// it looks.
const label = (name: string, theme: { $label?: string }) => theme.$label ?? name.charAt(0).toUpperCase() + name.slice(1)
const quote = (text: string) => `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
const described = (theme: { $description?: string }) =>
    theme.$description === undefined ? '' : `, description: ${quote(theme.$description)}`
files.set(
    join(CORE, 'src', 'lib', 'theme-list.ts'),
    [
        '// Generated by scripts/build-tokens.ts from tokens/tokens.json. Edit the JSON, not this file.\n',
        '/** Every theme in the tokens, by the name `data-theme` takes, the label a picker shows and a line on how it looks. */',
        'export const THEME_LIST: readonly { value: string; label: string; description?: string }[] = [',
        ...Object.entries(tokens.themes).map(
            ([name, theme]) => `    { value: ${quote(name)}, label: ${quote(label(name, theme))}${described(theme)} },`,
        ),
        ']\n',
    ].join('\n'),
)

// The breakpoints Tailwind's `md` and `lg` read, in px, for the media queries a script asks.
const breakpoint = (name: string): number => {
    const value = tokens.theme[`breakpoint-${name}`]
    const rem = typeof value === 'string' ? /^([\d.]+)rem$/.exec(value) : null
    if (rem === null) throw new Error(`tokens.json's theme sets breakpoint-${name} in rem`)
    return Number(rem[1]) * 16
}
files.set(
    join(CORE, 'src', 'lib', 'breakpoints.ts'),
    [
        '// Generated by scripts/build-tokens.ts from tokens/tokens.json. Edit the JSON, not this file.\n',
        "/** The breakpoints the tokens define, in px: below `md` a window is a phone or a foldable folded; from `lg` the shell's side panel is a column. */",
        `export const BREAKPOINTS = { md: ${String(breakpoint('md'))}, lg: ${String(breakpoint('lg'))} } as const`,
        '',
    ].join('\n'),
)

// The waits a script holds for, in ms, as the base theme sets them: how long a busy palette or dialog holds before it
// offers a way out, how long a read waits before it is shown, and how long a tooltip a tap showed stays up.
const duration = (name: string): number => {
    const value = base.light[name]
    const ms = typeof value === 'string' ? /^(\d+)ms$/.exec(value) : null
    if (ms === null) throw new Error(`tokens.json's ${BASE} theme sets ${name} in ms`)
    return Number(ms[1])
}
files.set(
    join(CORE, 'src', 'lib', 'durations.ts'),
    [
        '// Generated by scripts/build-tokens.ts from tokens/tokens.json. Edit the JSON, not this file.\n',
        '/** How long a busy palette or dialog holds, in ms, before it offers Stop waiting: the `busy-release` token. */',
        `export const BUSY_RELEASE = ${String(duration('busy-release'))}`,
        '',
        '/** How long a read is in flight, in ms, before a part shows it waits (a Searching line, earlier results dimmed): the `wait-shown` token. */',
        `export const WAIT_SHOWN = ${String(duration('wait-shown'))}`,
        '',
        '/** How long a tooltip a tap showed stays up, in ms, unless the next press closes it first: the `tip-hold` token. */',
        `export const TIP_HOLD = ${String(duration('tip-hold'))}`,
        '',
    ].join('\n'),
)

/** Theme files no theme in the tokens makes any more. */
const stale = existsSync(THEMES)
    ? readdirSync(THEMES)
          .map((file) => join(THEMES, file))
          .filter((path) => !files.has(path))
    : []

if (process.argv.includes('--check')) {
    const wrong = [...files].filter(([path, css]) => !existsSync(path) || readFileSync(path, 'utf8') !== css).map(([path]) => path)
    if (wrong.length > 0 || stale.length > 0) {
        console.error(`${[...wrong, ...stale].join(', ')}: not what tokens/tokens.json makes: run bun run tokens`)
        process.exit(1)
    }
    console.log(`the token CSS matches tokens/tokens.json: ${files.size} files`)
} else {
    mkdirSync(THEMES, { recursive: true })
    for (const [path, css] of files) writeFileSync(path, css)
    for (const path of stale) rmSync(path)
    console.log(
        `wrote the token CSS: tokens.css, themes.css and ${others.length} themes, with ${levels.length} density levels, and the theme list`,
    )
}
